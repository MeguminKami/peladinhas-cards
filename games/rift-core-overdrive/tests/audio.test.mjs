import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const listeners={};
const document={hidden:false,addEventListener(name,fn){listeners[name]=fn;}};
const source=(await readFile(new URL('../audio.js',import.meta.url),'utf8')).replace('export class ReactorAudio','globalThis.ReactorAudio=class ReactorAudio');
const sandbox={document,window:{},setInterval(){},Math};
vm.runInNewContext(source,sandbox);
const audio=new sandbox.ReactorAudio(()=>({music:true}));
audio.ctx={state:'running',currentTime:0};
audio.tracks={base:{}};
const notes=[];audio.note=(...args)=>notes.push(args);audio.drum=()=>{};
audio.next=.08;audio.schedule();
assert.equal(audio.step,4,'half a second of music is queued');
assert.ok(audio.next>=.5);
const step=audio.step,next=audio.next;
audio.schedule();assert.equal(audio.step,step,'repeated interactions do not duplicate beats');
document.hidden=true;audio.schedule();assert.equal(audio.step,step);
document.hidden=false;listeners.visibilitychange();
assert.equal(audio.next,next,'visibility does not reset queued music');
audio.ctx.currentTime=3;audio.schedule();
assert.ok(audio.step>step+15,'missed beats advance the phrase');
assert.ok(notes.slice(-3).every(n=>n[1]>=3),'no notes scheduled in the past');
let resumes=0;
audio.ctx.state='interrupted';audio.ctx.resume=()=>{resumes++;return Promise.reject(Error('gesture required'));};
listeners.touchend();listeners.pointerdown();
await new Promise(resolve=>setImmediate(resolve));
assert.equal(resumes,1,'only one pending resume');assert.equal(audio.resuming,null);
listeners.touchend();await new Promise(resolve=>setImmediate(resolve));
assert.equal(resumes,2,'retry available on next gesture');
console.log('Audio: lookahead, stalled clock, visibility, gesture recovery and rejected resumes passed.');
