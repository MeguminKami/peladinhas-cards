import {readFileSync,writeFileSync} from 'node:fs';

// Keep settlement identical to the browser; only replace the RNG and paths.
const source=new URL('../engine.js',import.meta.url);
let code=readFileSync(source,'utf8');
const start=code.indexOf('export function random(s){');
const end=code.indexOf('const pick=',start);
if(start<0||end<0)throw Error('Cannot locate browser RNG');
code=code.slice(0,start)+"export function random(s){s.draws++;return randomInt(0,0x100000000)/0x100000000;}\n"+code.slice(end);
code=code.replaceAll("from './","from '../");
writeFileSync(new URL('../integration/server-engine.mjs',import.meta.url),
 "// Generated by scripts/build-server-engine.mjs; same settlement math, server CSPRNG.\nimport {randomInt} from 'node:crypto';\n"+code);
